// ---------------------------------------------------------------------------
// Shared render callback — used for every social shortcode.
// ---------------------------------------------------------------------------
function sbo_render_social_icon( array $atts, string $tag ): string {
	$registry = sbo_social_icon_registry();

	if ( ! isset( $registry[ $tag ] ) ) {
		return '';
	}

	$icon = $registry[ $tag ];
	$url  = sbo_get( $icon['field'] );

	// Render nothing when the field is empty.
	if ( '' === $url ) {
		return '';
	}

	$atts = shortcode_atts(
		[
			'width'  => '2.1em',
			'height' => '2.1em',
			'fill'   => 'currentColor',
			'class'  => '',
		],
		$atts,
		$tag
	);

	$svg = sprintf(
		$icon['svg'],
		esc_attr( $atts['fill'] ),
		esc_attr( $atts['class'] ),
		esc_attr( $atts['width'] ),
		esc_attr( $atts['height'] )
	);

	return sprintf(
		'<a class="sbo-social-link" href="%s" target="_blank" rel="noopener noreferrer" itemprop="sameAs" aria-label="%s">%s</a>',
		esc_url( $url ),
		esc_attr( $icon['label'] ),
		$svg
	);
}

// ---------------------------------------------------------------------------
// Register all shortcodes on init.
// ---------------------------------------------------------------------------
add_action( 'init', function () {
	$tags = array_keys( sbo_social_icon_registry() );

	foreach ( $tags as $tag ) {
		add_shortcode( $tag, function ( $atts ) use ( $tag ) {
			return sbo_render_social_icon( (array) $atts, $tag );
		} );
	}
} );