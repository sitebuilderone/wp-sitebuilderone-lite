/**
 * Unified Render Function
 */
function sbo_render_social_shortcode( $atts, $tag ) {
    $registry = sbo_social_icon_registry();
    if ( ! isset( $registry[$tag] ) ) return '';

    $config = $registry[$tag];
    $url = function_exists('sbo_get') ? sbo_get($config['field']) : '';

    if ( empty($url) ) return '';

    // Fetch Global Defaults from sbo_options
    $default_width  = sbo_get('social-icon-width')  ?: '2.1em';
    $default_height = sbo_get('social-icon-height') ?: '2.1em';
    $default_fill   = sbo_get('social-icon-fill')   ?: ( $config['default_fill'] ?? 'currentColor' );

    // Merge attributes: Shortcode specific values override Global settings
    $a = shortcode_atts([
        'width'  => $default_width,
        'height' => $default_height,
        'fill'   => $default_fill,
        'class'  => 'm-1',
    ], $atts);

    $final_classes = trim( $config['base_class'] . ' ' . $a['class'] );

    $view_box = $config['view_box'] ?? '0 0 16 16';

    $svg = sprintf(
        '<svg xmlns="http://www.w3.org/2000/svg" viewBox="%s" fill="%s" style="color:%s" class="%s" width="%s" height="%s" aria-label="%s">%s</svg>',
        esc_attr($view_box),
        esc_attr($a['fill']),
        esc_attr($a['fill']),
        esc_attr($final_classes),
        esc_attr($a['width']),
        esc_attr($a['height']),
        esc_attr($config['label']),
        $config['svg']
    );

    return sprintf(
        '<a class="sbo-social-link" href="%s" target="_blank" rel="noopener noreferrer" itemprop="sameAs">%s</a>',
        esc_url($url),
        $svg
    );
}

/**
 * Aggregate shortcode to render all configured social icons.
 * Displays only icons whose corresponding URL value exists.
 * Use in templates/content:
* [sbo_social_all]
* Optional attributes: [sbo_social_all class="my-social-wrap" separator=" "]
*/

function sbo_render_all_social_shortcodes( $atts ) {
    $a = shortcode_atts(
        [
            'class'     => 'sbo-social-links',
            'separator' => '',
        ],
        $atts
    );

    $output = [];

    foreach ( array_keys( sbo_social_icon_registry() ) as $tag ) {
        $html = sbo_render_social_shortcode( [], $tag );
        if ( '' !== $html ) {
            $output[] = $html;
        }
    }

    if ( empty( $output ) ) {
        return '';
    }

    return sprintf(
        '<div class="%s">%s</div>',
        esc_attr( $a['class'] ),
        implode( $a['separator'], $output )
    );
}

/**
 * Register Shortcodes on Init
 */
add_action( 'init', function() {
    foreach ( array_keys( sbo_social_icon_registry() ) as $tag ) {
        add_shortcode( $tag, function($atts) use ($tag) {
            return sbo_render_social_shortcode($atts, $tag);
        });
    }

    add_shortcode( 'sbo_social_all', 'sbo_render_all_social_shortcodes' );
});

