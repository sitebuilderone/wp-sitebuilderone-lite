/**
 * Unified Render Function
 */
function sbo_render_social_shortcode( $atts, $tag ) {
    $registry = sbo_social_icon_registry();
    if ( ! isset( $registry[$tag] ) ) return '';

    $config = $registry[$tag];
    $url = function_exists('sbo_get') ? sbo_get($config['field']) : '';

    if ( empty($url) ) return '';

    // Fetch Global Defaults from sbo_options
    $default_width  = sbo_get('social-icon-width')  ?: '2.1em';
    $default_height = sbo_get('social-icon-height') ?: '2.1em';
    $default_fill   = sbo_get('social-icon-fill')   ?: 'currentColor';

    // Merge attributes: Shortcode specific values override Global settings
    $a = shortcode_atts([
        'width'  => $default_width,
        'height' => $default_height,
        'fill'   => $default_fill,
        'class'  => '',
    ], $atts);

    $final_classes = trim( $config['base_class'] . ' ' . $a['class'] );

    $svg = sprintf(
        '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 16 16" fill="%s" class="%s" width="%s" height="%s" aria-label="%s">%s</svg>',
        esc_attr($a['fill']),
        esc_attr($final_classes),
        esc_attr($a['width']),
        esc_attr($a['height']),
        esc_attr($config['label']),
        $config['svg']
    );

    return sprintf(
        '<a class="sbo-social-link" href="%s" target="_blank" rel="noopener noreferrer" itemprop="sameAs">%s</a>',
        esc_url($url),
        $svg
    );
}

/**
 * Register Shortcodes on Init
 */
add_action( 'init', function() {
    foreach ( array_keys( sbo_social_icon_registry() ) as $tag ) {
        add_shortcode( $tag, function($atts) use ($tag) {
            return sbo_render_social_shortcode($atts, $tag);
        });
    }
});

